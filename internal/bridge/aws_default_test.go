func TestFilterHostDefaultSnapshotPreservesEqualsInValues(t *testing.T) {
	filtered, state, err := FilterHostDefaultSnapshot(HostAWSDirectorySnapshot{
		Config:      []byte("[default]\noutput=prefix=value\n"),
		Credentials: []byte("[default]\naws_access_key_id=AKIA=part\naws_secret_access_key=secret==\naws_session_token=a=b=c\n"),
	})
	if err != nil || state != HostDefaultAvailable {
		t.Fatalf("filter state = %q, %v", state, err)
	}
	for _, expected := range [][]byte{[]byte("output=prefix=value\n"), []byte("aws_access_key_id=AKIA=part\n"), []byte("aws_secret_access_key=secret==\n"), []byte("aws_session_token=a=b=c\n")} {
		if !bytes.Contains(append(filtered.Config, filtered.Credentials...), expected) {
			t.Fatalf("filtered output omitted %q", expected)
		}
	}
}

