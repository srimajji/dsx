const completeTemporaryCredentials = `[default]
aws_access_key_id = access-value
aws_secret_access_key = secret-value
aws_session_token = token-value
`

func TestFilterHostDefaultSnapshotAcceptsLeappStyleTemporaryDefault(t *testing.T) {
	snapshot := HostAWSDirectorySnapshot{
		Config:      []byte("[default]\noutput = json\nregion = us-west-2\n[profile engineering]\nregion=eu-west-1\n"),
		Credentials: []byte(completeTemporaryCredentials + "[engineering]\naws_access_key_id=named-access\naws_secret_access_key=named-secret\n"),
	}
	filtered, state, err := FilterHostDefaultSnapshot(snapshot)
	if err != nil || state != HostDefaultAvailable {
		t.Fatalf("filter state = %q, %v", state, err)
	}
	if got, want := string(filtered.Config), "[default]\noutput=json\nregion=us-west-2\n"; got != want {
		t.Fatalf("config = %q, want %q", got, want)
	}
	if got, want := string(filtered.Credentials), "[default]\naws_access_key_id=access-value\naws_secret_access_key=secret-value\naws_session_token=token-value\n"; got != want {
		t.Fatalf("credentials = %q, want %q", got, want)
	}
	if bytes.Contains(filtered.Config, []byte("engineering")) || bytes.Contains(filtered.Credentials, []byte("named-")) {
		t.Fatal("named profile reached filtered snapshot")
	}
}

