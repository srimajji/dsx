func TestFilterHostDefaultSnapshotEnforcesSizeAndStructuralLimits(t *testing.T) {
	t.Run("source bytes", func(t *testing.T) {
		input := bytes.Repeat([]byte{'x'}, maxHostDefaultSourceBytes+1)
		_, _, err := FilterHostDefaultSnapshot(HostAWSDirectorySnapshot{Config: input, Credentials: []byte(completeTemporaryCredentials)})
		if !errors.Is(err, ErrHostDefaultOversized) {
			t.Fatalf("error = %v", err)
		}
	})

	for _, test := range []struct {
		name  string
		input func() []byte
	}{
		{name: "section count", input: func() []byte {
			var input strings.Builder
			for index := 0; index <= maxHostDefaultSections; index++ {
				input.WriteString("[section-")
				input.WriteString(strings.Repeat("x", index/maxHostDefaultSections))
				input.WriteByte(byte('A' + index%26))
				input.WriteString(strings.Repeat("z", index/26))
				input.WriteString("]\n")
			}
			return []byte(input.String())
		}},
		{name: "key count", input: func() []byte {
			var input strings.Builder
			input.WriteString("[default]\n")
			for index := 0; index <= maxHostDefaultKeys; index++ {
				input.WriteString("key")
				input.WriteString(base26HostDefaultTestName(index))
				input.WriteString("=value\n")
			}
			return []byte(input.String())
		}},
		{name: "section name bytes", input: func() []byte {
			return []byte("[" + strings.Repeat("a", maxHostDefaultNameBytes+1) + "]\n")
		}},
		{name: "key name bytes", input: func() []byte {
			return []byte("[default]\n" + strings.Repeat("a", maxHostDefaultKeyBytes+1) + "=value\n")
		}},
		{name: "line bytes", input: func() []byte {
			return []byte("[default]\nregion=" + strings.Repeat("a", maxHostDefaultLineBytes) + "\n")
		}},
	} {
		t.Run(test.name, func(t *testing.T) {
			_, state, err := FilterHostDefaultSnapshot(HostAWSDirectorySnapshot{Config: test.input(), Credentials: []byte(completeTemporaryCredentials)})
			if !errors.Is(err, ErrHostDefaultLimitExceeded) || state != HostDefaultUnavailable {
				t.Fatalf("filter state = %q, error = %v", state, err)
			}
		})
	}
}

func TestFilterHostDefaultSnapshotIsDeterministic(t *testing.T) {
	left, leftState, leftErr := FilterHostDefaultSnapshot(HostAWSDirectorySnapshot{
		Config:      []byte("[default]\nregion = us-west-1\noutput=json\n"),
		Credentials: []byte("[default]\naws_session_token=token\naws_access_key_id=access\naws_secret_access_key=secret\n"),
	})
	right, rightState, rightErr := FilterHostDefaultSnapshot(HostAWSDirectorySnapshot{
		Config:      []byte("; generated\r\n[default]\r\noutput = json\r\nregion=us-west-1\r\n"),
		Credentials: []byte("[default]\r\nAWS_SECRET_ACCESS_KEY = secret\r\nAWS_ACCESS_KEY_ID=access\r\nAWS_SESSION_TOKEN = token\r\n"),
	})
	if leftErr != nil || rightErr != nil || leftState != HostDefaultAvailable || rightState != HostDefaultAvailable {
		t.Fatalf("states = %q/%q, errors = %v/%v", leftState, rightState, leftErr, rightErr)
	}
	if !bytes.Equal(left.Config, right.Config) || !bytes.Equal(left.Credentials, right.Credentials) {
		t.Fatalf("non-deterministic output: %#v != %#v", left, right)
	}
}

func TestFilterHostDefaultSnapshotErrorsNeverContainSourceBytes(t *testing.T) {
	secret := "never-echo-this-secret-value"
	inputs := [][]byte{
		[]byte("[default]\naws_secret_access_key=" + secret + "\nmalformed continuation\n"),
		append([]byte("[default]\nregion="+secret), 0),
		bytes.Repeat([]byte(secret), maxHostDefaultSourceBytes/len(secret)+1),
	}
	for _, input := range inputs {
		_, _, err := FilterHostDefaultSnapshot(HostAWSDirectorySnapshot{Config: input, Credentials: []byte(completeTemporaryCredentials)})
		if err == nil {
			t.Fatal("invalid secret-bearing source was accepted")
		}
		if strings.Contains(err.Error(), secret) {
			t.Fatalf("error exposed source bytes: %q", err)
		}
	}
}

func assertEmptyHostDefaultSnapshot(t *testing.T, snapshot HostAWSDirectorySnapshot) {
	t.Helper()
	if len(snapshot.Config) != 0 || len(snapshot.Credentials) != 0 {
		t.Fatalf("non-available result retained bytes: config=%d credentials=%d", len(snapshot.Config), len(snapshot.Credentials))
	}
}

func base26HostDefaultTestName(value int) string {
	var encoded [8]byte
	position := len(encoded)
	for {
		position--
		encoded[position] = byte('a' + value%26)
		value /= 26
		if value == 0 {
			return string(encoded[position:])
		}
	}
}
